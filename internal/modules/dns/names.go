package dns

// Local names: when the operator names a device in FlowSight, they can also
// give it a DNS name, so other devices reach it as nas.grio.co and a lookup
// of its address answers with that name.
//
// A name goes to every resolver the network's devices ask. The gateway's
// Unbound gets it from a FlowSight include (flowsight-names.conf), never
// from the operator's own host overrides, and it is loaded into the running
// resolver with unbound-control so the cache is not flushed. Each connected
// Pi-hole gets it as a local record, because a Pi-hole answers its clients
// from its own records and forwards everything else upstream, never to the
// gateway: a name only on the gateway is invisible to anyone using the
// Pi-hole directly.
//
// A device's IPv4 address changes when its lease does. With "follow" on,
// the name moves with the device: a job re-points it at the address the
// device's hardware address holds now.

