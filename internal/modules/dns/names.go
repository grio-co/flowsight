func (m *Module) targets() (bool, []pihole.HostsTarget) {
	var t []pihole.HostsTarget
	if p := m.pihole(); p != nil {
		t = p.Targets()
	}
	return m.ctx.Platform.UnboundInclude != "", t
}

func (m *Module) apiNames(r *core.Req) (any, error) {
	recs := m.loadNames()
	gw, targets := m.targets()
	rows := make([]map[string]any, len(recs))
	var wg sync.WaitGroup
	for i, rec := range recs {
		wg.Add(1)
		go func(i int, rec localName) {
			defer wg.Done()
			rows[i] = map[string]any{"record": rec, "status": m.statusOf(rec, targets)}
		}(i, rec)
	}
	wg.Wait()
	return map[string]any{"names": rows, "domains": m.domains(), "gateway": gw, "piholes": targets}, nil
}

func (m *Module) apiNameSuggest(r *core.Req) (any, error) {
	ip, err := r.QSafe("ip", "", 64)
	if err != nil {
		return nil, err
	}
	if net.ParseIP(ip) == nil {
		return nil, core.BadRequest("ip must be an address")
	}
	display, err := r.QSafe("name", "", 80)
	if err != nil {
		return nil, err
	}
	mac := ""
	if rows, _ := m.ctx.Store.Rows(`SELECT COALESCE(mac,'') AS mac, COALESCE(name,'') AS name FROM hosts WHERE ip=?`, ip); len(rows) > 0 {
		mac, _ = rows[0]["mac"].(string)
		if display == "" {
			display, _ = rows[0]["name"].(string)
		}
	}
	gw, targets := m.targets()
	var existing *localName
	for _, rec := range m.loadNames() {
		if (mac != "" && strings.EqualFold(rec.MAC, mac)) || contains(rec.Addrs, ip) {
			rc := rec
			existing = &rc
			break
		}
	}
	_, rev := m.hostEntries()
	// What already answers for this device's addresses, so the page can
	// say "192.168.1.44 already reads as printer.grio.co".
	ptrs := map[string][]string{}
	for _, a := range m.devAddrs(ip, mac) {
		addr := a["ip"].(string)
		if n := rev[addr]; len(n) > 0 {
			ptrs[addr] = n
		}
	}
	doms := m.domains()
	return map[string]any{"ip": ip, "mac": mac, "label": labelFrom(display), "domains": doms,
		"addresses": m.devAddrs(ip, mac), "existing": existing, "reverse_taken": ptrs,
		"gateway": gw, "piholes": targets, "can_follow": mac != ""}, nil
}

func (m *Module) apiNameSave(r *core.Req) (any, error) {
	var in struct {
		Label     string   `json:"label"`
		Domain    string   `json:"domain"`
		Display   string   `json:"display"`
		IP        string   `json:"ip"`
		MAC       string   `json:"mac"`
		Addresses []string `json:"addresses"`
		Follow    bool     `json:"follow"`
		Gateway   bool     `json:"gateway"`
		Piholes   []string `json:"piholes"`
		Replace   string   `json:"replace"`
	}
	if err := r.Decode(&in); err != nil {
		return nil, err
	}
	label, domain := strings.ToLower(strings.TrimSpace(in.Label)), strings.Trim(strings.ToLower(strings.TrimSpace(in.Domain)), ".")
	if !labelRe.MatchString(label) {
		return nil, core.BadRequest("the name %q is not a valid DNS label: letters, digits and dashes, up to 63, not starting or ending with a dash", in.Label)
	}
	if !domainRe.MatchString(domain) || !strings.Contains(domain+".", ".") {
		return nil, core.BadRequest("the domain %q is not valid", in.Domain)
	}
	fqdn := label + "." + domain
	var addrs []string
	for _, a := range in.Addresses {
		p := net.ParseIP(strings.TrimSpace(a))
		if p == nil || p.IsLoopback() || p.IsUnspecified() || p.IsMulticast() || p.IsLinkLocalUnicast() {
			return nil, core.BadRequest("%q is not an address a device can be reached at", a)
		}
		if !contains(addrs, p.String()) {
			addrs = append(addrs, p.String())
		}
	}
	if len(addrs) == 0 {
		return nil, core.BadRequest("choose at least one address")
	}
	if !in.Gateway && len(in.Piholes) == 0 {
		return nil, core.BadRequest("choose where the name goes: the gateway resolver, a Pi-hole, or both")
	}
	mac := strings.ToLower(strings.TrimSpace(in.MAC))
	if mac == "" && in.IP != "" {
		if rows, _ := m.ctx.Store.Rows(`SELECT COALESCE(mac,'') AS mac FROM hosts WHERE ip=?`, in.IP); len(rows) > 0 {
			mac, _ = rows[0]["mac"].(string)
			mac = strings.ToLower(mac)
		}
	}
	_, targets := m.targets()
	var piholes []string
	for _, u := range in.Piholes {
		for _, t := range targets {
			if u == t.URL || u == t.Host {
				if !t.Writable {
					return nil, core.BadRequest("Pi-hole %s does not let FlowSight change its records; turn on “Permit app password to modify config” there, or leave it out", t.Host)
				}
				if !contains(piholes, t.URL) {
					piholes = append(piholes, t.URL)
				}
			}
		}
	}
	fwd, rev := m.hostEntries()
	if have := fwd[fqdn]; len(have) > 0 && in.Gateway {
		return nil, core.BadRequest("%s is already a host override on the gateway (%s); choose another name or change it in OPNsense › Unbound › Overrides", fqdn, strings.Join(have, ", "))
	}
	var noPTR []string
	for _, a := range addrs {
		if len(rev[a]) > 0 {
			noPTR = append(noPTR, a)
		}
	}

	namesMu.Lock()
	defer namesMu.Unlock()
	before := m.loadNames()
	var after, old []localName
	now := time.Now().Unix()
	created := now
	for _, rec := range before {
		same := rec.FQDN == fqdn || (in.Replace != "" && rec.FQDN == in.Replace) || (mac != "" && strings.EqualFold(rec.MAC, mac))
		if same {
			if rec.FQDN == fqdn && mac != "" && rec.MAC != "" && !strings.EqualFold(rec.MAC, mac) {
				return nil, core.BadRequest("%s already names another device (%s)", fqdn, rec.MAC)
			}
			old = append(old, rec)
			created = rec.Created
			continue
		}
		for _, a := range addrs {
			if contains(rec.Addrs, a) {
				return nil, core.BadRequest("%s already has the name %s in FlowSight; remove that first", a, rec.FQDN)
			}
		}
		after = append(after, rec)
	}
	rec := localName{FQDN: fqdn, Label: label, Domain: domain, Display: strings.TrimSpace(in.Display), MAC: mac, Addrs: addrs,
		Follow: in.Follow && mac != "", Gateway: in.Gateway, Piholes: piholes, NoPTR: noPTR, Created: created, Updated: now, By: r.User}
	after = append(after, rec)

	result := map[string]any{"record": rec}
	var notes []string
	if len(noPTR) > 0 {
		notes = append(notes, "The gateway already answers the reverse lookup for "+strings.Join(noPTR, ", ")+" from an OPNsense host override, so FlowSight adds the forward name only there.")
	}
	if in.Gateway || anyGateway(old) {
		if err := m.applyGateway(old, []localName{rec}, after); err != nil {
			result["gateway_error"] = err.Error()
		} else if in.Gateway {
			result["gateway"] = "ok"
		}
	}
	result["piholes"] = m.applyPiholes(old, []localName{rec}, r.User)
	if err := m.ctx.Store.KVSet(namesKV, after); err != nil {
		return nil, err
	}
	summary := fmt.Sprintf("DNS name %s -> %s", fqdn, strings.Join(addrs, ", "))
	if len(old) > 0 && old[0].FQDN != fqdn {
		summary += " (was " + old[0].FQDN + ")"
	}
	_ = m.ctx.Store.RecordChange("dns", "name:"+fqdn, r.User, "", strings.Join(addrs, ","), "", summary)
	result["notes"] = notes
	result["ok"] = result["gateway_error"] == nil && !anyError(result["piholes"])
	return result, nil
}

func anyGateway(recs []localName) bool {
	for _, r := range recs {
		if r.Gateway {
			return true
		}
	}
	return false
}

func anyError(v any) bool {
	list, _ := v.([]map[string]any)
	for _, x := range list {
		if x["error"] != nil {
			return true
		}
	}
	return false
}

func (m *Module) apiNameRemove(r *core.Req) (any, error) {
	var in struct {
		FQDN string `json:"fqdn"`
	}
	if err := r.Decode(&in); err != nil {
		return nil, err
	}
	namesMu.Lock()
	defer namesMu.Unlock()
	before := m.loadNames()
	var after, gone []localName
	for _, rec := range before {
		if rec.FQDN == strings.ToLower(strings.TrimSpace(in.FQDN)) {
			gone = append(gone, rec)
		} else {
			after = append(after, rec)
		}
	}
	if len(gone) == 0 {
		return nil, core.NotFound("no FlowSight name %s", in.FQDN)
	}
	result := map[string]any{}
	if anyGateway(gone) {
		if err := m.applyGateway(gone, nil, after); err != nil {
			result["gateway_error"] = err.Error()
		}
	}
	result["piholes"] = m.applyPiholes(gone, nil, r.User)
	if err := m.ctx.Store.KVSet(namesKV, after); err != nil {
		return nil, err
	}
	_ = m.ctx.Store.RecordChange("dns", "name:"+gone[0].FQDN, r.User, strings.Join(gone[0].Addrs, ","), "", "", "DNS name "+gone[0].FQDN+" removed")
	result["ok"] = result["gateway_error"] == nil && !anyError(result["piholes"])
	return result, nil
}

// followNames re-points names whose device moved to a new IPv4 address.
func (m *Module) followNames() error {
	namesMu.Lock()
	defer namesMu.Unlock()
	recs := m.loadNames()
	changed := false
	for i, rec := range recs {
		if !rec.Follow || rec.MAC == "" {
			continue
		}
		rows, _ := m.ctx.Store.Rows(`SELECT ip FROM hosts WHERE lower(mac)=? AND ip NOT LIKE '%:%' AND last_seen>=? ORDER BY last_seen DESC LIMIT 1`,
			strings.ToLower(rec.MAC), time.Now().Add(-6*time.Hour).Unix())
		if len(rows) == 0 {
			continue
		}
		now, _ := rows[0]["ip"].(string)
		var oldV4 []string
		var keep []string
		for _, a := range rec.Addrs {
			if p := net.ParseIP(a); p != nil && p.To4() != nil {
				oldV4 = append(oldV4, a)
			} else {
				keep = append(keep, a)
			}
		}
		if len(oldV4) != 1 || oldV4[0] == now || now == "" {
			continue // follows a single IPv4 address only
		}
		// Another FlowSight name already on that address wins.
		taken := false
		for j, other := range recs {
			if j != i && contains(other.Addrs, now) {
				taken = true
			}
		}
		if taken {
			continue
		}
		prev := rec
		rec.Addrs = append([]string{now}, keep...)
		rec.NoPTR = nil
		_, rev := m.hostEntries()
		for _, a := range rec.Addrs {
			if len(rev[a]) > 0 {
				rec.NoPTR = append(rec.NoPTR, a)
			}
		}
		rec.Updated = time.Now().Unix()
		recs[i] = rec
		if rec.Gateway {
			if err := m.applyGateway([]localName{prev}, []localName{rec}, recs); err != nil {
				m.ctx.Log.Warn("local name follow", "name", rec.FQDN, "error", err)
			}
		}
		m.applyPiholes([]localName{prev}, []localName{rec}, "flowsightd")
		_ = m.ctx.Store.RecordChange("dns", "name:"+rec.FQDN, "flowsightd", oldV4[0], now, "",
			fmt.Sprintf("DNS name %s followed its device from %s to %s", rec.FQDN, oldV4[0], now))
		changed = true
	}
	if changed {
		return m.ctx.Store.KVSet(namesKV, recs)
	}
	return nil
}

